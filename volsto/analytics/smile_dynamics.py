def _basis(features: FloatArray, degree: int) -> FloatArray:
    """``[1, x_j, x_j x_k, …]`` up to ``degree`` (with repetition) on standardised features
    (the basis of :func:`volsto.risk.estimators.conditional_greeks`)."""
    n, d = features.shape
    cols = [np.ones(n)]
    for deg in range(1, degree + 1):
        for combo in itertools.combinations_with_replacement(range(d), deg):
            cols.append(np.prod(features[:, list(combo)], axis=1))
    return np.column_stack(cols)


@dataclass
class _Horizon:
    """State at ``t`` and log-spot at ``T`` for every path."""

    t: float
    T: float
    ln_s_t: FloatArray
    factors_t: FloatArray
    ln_s_T: FloatArray
    ln_f_t: float
    ln_f_T: float
    df_T: float


def _simulate_horizon(model: Model, t: float, T: float, sim: SimConfig) -> _Horizon:
    if not 0.0 < t < T:
        raise ValueError("need 0 < t < T")
    grid = TimeGrid.build([t, T], sim.dt_max, calibration_grid=model.required_times())
    idx = grid.fixing_index
    ct, cT = idx[t], idx[T]
    draws = GaussianDraws(sim.seed, sim.n_paths, grid.n_steps, model.n_brownians, sim.antithetic)
    n = sim.n_paths
    ln_s_t = np.empty(n)
    ln_s_T = np.empty(n)
    fac = np.empty((n, model.n_factors))
    for p0, p1 in sim.chunk_ranges(grid.n_records, model.n_factors):
        paths = model.simulate_chunk(grid, draws, p0, p1, sim.scheme)
        ln_s_t[p0:p1] = paths.log_spot_at(ct)
        ln_s_T[p0:p1] = paths.log_spot_at(cT)
        fac[p0:p1] = paths.factors_at(ct)
    fc = model.forward_curve
    return _Horizon(
        t,
        T,
        ln_s_t,
        fac,
        ln_s_T,
        float(fc.log_forward(t)),
        float(fc.log_forward(T)),
        float(fc.rate_curve.df(T)),
    )


def _fit(x: FloatArray, y: FloatArray) -> tuple[FloatArray, float]:
    beta, *_ = np.linalg.lstsq(x, y, rcond=None)
    resid = y - x @ beta
    var_y = float(y.var())
    r2 = 1.0 - float(resid.var()) / var_y if var_y > 0 else 1.0
    return np.asarray(beta, dtype=np.float64), r2


def _batches(n: int, n_batches: int, antithetic: bool) -> list[slice]:
    unit = 2 if antithetic else 1
    size = (n // (n_batches * unit)) * unit
    if size < max(unit, 8):
        raise ValueError("too few paths for the requested number of batches")
    return [slice(b * size, (b + 1) * size) for b in range(n_batches)]


def _batch_stat(
    fn: Callable[[slice], FloatArray], n: int, n_batches: int, antithetic: bool
) -> tuple[FloatArray, FloatArray]:
    """Full-sample value of ``fn`` (vector statistic) with batch-means standard errors."""
    full = np.atleast_1d(fn(slice(0, n)))
    vals = np.stack([np.atleast_1d(fn(s)) for s in _batches(n, n_batches, antithetic)])
    return full, np.asarray(vals.std(axis=0, ddof=1) / np.sqrt(n_batches), dtype=np.float64)


def _atmf_vol_from_normalised_price(price: FloatArray, m: float, tau: float) -> FloatArray:
    """ATMF Black inversion of the undiscounted normalised call ``E[(S_T/S_t − m)⁺ | ·]`` with
    forward = strike = ``m``: ``price = m [2 N(σ√τ/2) − 1]``."""
    x = np.clip(price / m, 1e-12, 1.0 - 1e-12)
    return np.asarray(2.0 / np.sqrt(tau) * ndtri(0.5 * (x + 1.0)), dtype=np.float64)


