@dataclass(frozen=True)
class SSRShortHorizon:
    """SSR from the regression of the conditional ATMF vol at ``t`` on ``ln S_t`` across paths."""

    T: float
    t: float
    degree: int
    n_batches: int
    R: float
    R_stderr: float
    slope: float
    slope_stderr: float
    skew: float
    skew_stderr: float
    atmf_vol_0: float
    mean_conditional_vol: float
    r2: float
    n_paths: int

    def __repr__(self) -> str:
        return (
            f"SSRShortHorizon(T={self.T:g}, t={self.t:.4g}: R = {self.R:.4f} ± "
            f"{self.R_stderr:.4f}, slope = {self.slope:.4f} ± {self.slope_stderr:.4f}, "
            f"S_T = {self.skew:.4f} ± {self.skew_stderr:.4f}, r2 = {self.r2:.4f})"
        )


def ssr_short_horizon(
    model: Model,
    T: float,
    *,
    sim: SimConfig,
    t: float = 1.0 / 52.0,
    degree: int = 3,
    n_batches: int = 10,
    skew_h: float = 0.01,
) -> SSRShortHorizon:
    """The independent short-horizon estimator of the SSR (SPEC §4.4, book eq. 9.3 read over
    ``[0, t]``): simulate to ``t``; the ATMF-at-``t`` call of maturity ``T`` has strike ``S_t
    F(T)/F(t)`` and its normalised payoff ``(S_T/S_t − m)⁺`` is regressed on the polynomial
    basis in ``(ln S_t, X_t)`` (as :func:`volsto.risk.estimators.conditional_greeks`); the fitted
    conditional price inverts to ``σ̂_T(t)`` (Black, forward = strike); ``slope`` is the
    regression coefficient of ``σ̂_T(t)`` on ``ln S_t`` across paths and ``R = slope / S_T`` with
    ``S_T`` the ``t = 0`` ATMF skew on the same paths.  Standard errors: batch means over
    ``n_batches`` pair-aligned batches for the slope, per-path for the skew, combined in
    quadrature.  Slow: ``tests/test_smile_dynamics.py::test_ssr_short_horizon_slow``.
    """
    if degree < 1 or n_batches < 2 or skew_h <= 0:
        raise ValueError("need degree >= 1, n_batches >= 2, skew_h > 0")
    hz = _simulate_horizon(model, t, T, sim)
    tau = T - t
    m = float(np.exp(hz.ln_f_T - hz.ln_f_t))
    y = np.maximum(np.exp(hz.ln_s_T - hz.ln_s_t) - m, 0.0)
    raw = np.column_stack([hz.ln_s_t, hz.factors_t])
    mean = raw.mean(axis=0)
    scale = np.where(raw.std(axis=0) > 0, raw.std(axis=0), 1.0)
    x = _basis((raw - mean) / scale, degree)
    n = sim.n_paths
    r2_full = 0.0
    mean_vol = 0.0

    def stat(s: slice) -> FloatArray:
        nonlocal r2_full, mean_vol
        beta, r2 = _fit(x[s], y[s])
        sig = _atmf_vol_from_normalised_price(x[s] @ beta, m, tau)
        ls = hz.ln_s_t[s]
        slope = float(np.cov(sig, ls)[0, 1] / ls.var(ddof=1))
        if s.start == 0 and s.stop == n:
            r2_full, mean_vol = r2, float(sig.mean())
        return np.array([slope])

    slope, slope_se = _batch_stat(stat, n, n_batches, sim.antithetic)
    # t = 0 ATMF skew and vol of maturity T on the same paths
    F_T = float(np.exp(hz.ln_f_T))
    ks = np.array([-skew_h, 0.0, skew_h])
    K = F_T * np.exp(ks)
    cps = np.array([-1, 1, 1])
    pays = np.stack(
        [np.maximum(c * (np.exp(hz.ln_s_T) - k), 0.0) * hz.df_T for k, c in zip(K, cps)], axis=1
    )
    iv = implied_vol(pays.mean(axis=0), F_T, K, T, cps, hz.df_T)
    vega = black_vega(F_T, K, T, iv, hz.df_T)
    samp = _pairs(pays, sim.antithetic) / vega[None, :]
    skew = float((iv[2] - iv[0]) / (2.0 * skew_h))
    skew_se = _se((samp[:, 2] - samp[:, 0]) / (2.0 * skew_h))
    R = float(slope[0]) / skew
    R_se = abs(R) * float(np.hypot(slope_se[0] / slope[0], skew_se / skew))
    return SSRShortHorizon(
        float(T),
        float(t),
        int(degree),
        int(n_batches),
        R,
        R_se,
        float(slope[0]),
        float(slope_se[0]),
        skew,
        skew_se,
        float(iv[1]),
        mean_vol,
        r2_full,
        int(n),
    )


