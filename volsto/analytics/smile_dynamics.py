@dataclass
class _Quotes:
    """Implied vols of the strikes ``F_T e^k`` for several maturities on one path set, with the
    per-path linearised vol samples ``payoff / vega`` (antithetic pairs averaged)."""

    Ts: FloatArray
    ks: FloatArray
    forward: FloatArray  # (nT,)
    iv: FloatArray  # (nT, nk)
    samples: FloatArray  # (n_samples, nT, nk)


def _atmf_quotes(
    model: Model,
    Ts: FloatArray,
    ks: FloatArray,
    mc: MonteCarlo,
    grid: TimeGrid,
    draws: GaussianDraws,
) -> _Quotes:
    fc = model.forward_curve
    rc = fc.rate_curve
    F = np.asarray(fc.forward(Ts), dtype=np.float64)
    df = np.asarray(rc.df(Ts), dtype=np.float64)
    # calls at every strike: the per-path difference between the ±h strikes is then a call
    # spread bounded by 2hF (out-of-the-money puts below the forward would make it a full payoff)
    products = [
        EuropeanOption(float(F[i] * np.exp(k)), float(T), 1, rc)
        for i, T in enumerate(Ts)
        for k in ks
    ]
    res = mc.price_many(products, model, grid=grid, draws=draws, keep_payoffs=True)
    nT, nk = Ts.size, ks.size
    means = np.array([r.mean for r in res]).reshape(nT, nk)
    pays = np.stack([_pairs(np.asarray(r.payoffs), mc.cfg.antithetic) for r in res], axis=1)
    K = F[:, None] * np.exp(ks)[None, :]
    iv = implied_vol(means, F[:, None], K, Ts[:, None], 1, df[:, None])
    if not np.all(np.isfinite(iv)):
        raise ValueError("implied-vol inversion failed for an ATMF quote")
    vega = black_vega(F[:, None], K, Ts[:, None], iv, df[:, None])
    samples = pays.reshape(pays.shape[0], nT, nk) / vega[None, :, :]
    return _Quotes(Ts, ks, F, np.asarray(iv, dtype=np.float64), samples)


def _skew(q: _Quotes, h: float) -> tuple[FloatArray, FloatArray]:
    """``(S_T, per-path samples)`` from the ``±h`` columns of quotes with ``ks = (−h, 0, h)``."""
    skew = (q.iv[:, 2] - q.iv[:, 0]) / (2.0 * h)
    samples = (q.samples[:, :, 2] - q.samples[:, :, 0]) / (2.0 * h)
    return np.asarray(skew, dtype=np.float64), np.asarray(samples, dtype=np.float64)


def _grid_and_draws(
    model: Model, Ts: FloatArray, sim: SimConfig
) -> tuple[MonteCarlo, TimeGrid, GaussianDraws]:
    mc = MonteCarlo(sim)
    rc = model.forward_curve.rate_curve
    probe = [EuropeanOption(model.spot, float(T), 1, rc) for T in Ts]
    grid = mc.build_grid(probe, model)
    return mc, grid, mc.draws_for(grid, model)


def _bump_scales(model: Model) -> FloatArray:
    """Per state coordinate: ``ln S`` moves by ``ε σ_0``, each factor by ``ε``."""
    rho_s, _ = factor_loadings(model)
    return np.concatenate(([initial_vol(model)], np.ones(rho_s.size)))


