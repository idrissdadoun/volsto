def kernel_of(model: Model) -> BergomiSV:
    """The Bergomi kernel of a ``BergomiSV`` or ``LSV`` model."""
    if isinstance(model, BergomiSV):
        return model
    if isinstance(model, LSV):
        return model.kernel
    raise TypeError("this analytic needs a BergomiSV or LSV model")


def factor_loadings(model: Model) -> tuple[FloatArray, FloatArray]:
    """``(ρ_S, corr_X)`` of the model's factors: the kernel's ``corr(W^S, W^i)`` and factor
    correlation matrix for a Bergomi-based model, empty arrays for a factor-less model (local
    vol, Black–Scholes), whose smile dynamics is spot-driven only."""
    if isinstance(model, BergomiSV | LSV):
        k = kernel_of(model)
        return k.rho_s, k.corr_x
    if model.n_factors == 0:
        return np.zeros(0), np.zeros((0, 0))
    raise TypeError("smile-dynamics analytics need a BergomiSV, LSV or factor-less model")


def initial_vol(model: Model) -> float:
    """``σ_0 = L(0, S_0) sqrt(ξ_0^0)`` (``L = 1`` for pure SV; the kernel's ``x0`` included)."""
    v0 = model.instantaneous_variance(model.initial_state(2))
    return float(np.sqrt(float(np.mean(v0))))


def state_covariance(model: Model) -> FloatArray:
    """Instantaneous covariance per unit time of ``(ln S, X¹, …, X^nf)`` at ``t = 0`` (book
    §12.4.3): ``E[(d ln S)²] = σ_0² dt``, ``E[d ln S dX^i] = ρ_SXi σ_0 dt``, ``E[dX^i dX^j] =
    ρ_ij dt``."""
    rho_s, corr_x = factor_loadings(model)
    s0 = initial_vol(model)
    nf = rho_s.size
    cov = np.empty((1 + nf, 1 + nf))
    cov[0, 0] = s0 * s0
    cov[0, 1:] = cov[1:, 0] = rho_s * s0
    cov[1:, 1:] = corr_x
    return cov


def state_bump(model: Model, *, d_ln_s: float = 0.0, dx: ArrayLike | None = None) -> Model:
    """The model with its initial state bumped: ``ln S_0 → ln S_0 + d_ln_s`` with the local
    volatility held fixed in spot (the LSV's :meth:`~volsto.models.lsv.LSV.bump` re-anchors
    ``L``; a :class:`~volsto.models.localvol.LocalVol` gets its Dupire surface re-anchored the
    same way — the book's fixed local volatility function; other models through their own
    ``bump(spot=)``) and ``X_0 → X_0 + dx`` for the Bergomi-based models."""
    dx_ = None if dx is None else np.asarray(dx, dtype=np.float64)
    moves_factors = dx_ is not None and bool(np.any(dx_ != 0.0))
    if isinstance(model, LocalVol):
        if moves_factors:
            raise ValueError("a local-vol model has no factor state to bump")
        if d_ln_s == 0.0:
            return model
        fc = model.forward_curve.with_spot(model.spot * float(np.exp(d_ln_s)))
        return LocalVol(model.local_vol.reanchored(fc), fc)
    kwargs: dict[str, object] = {}
    if d_ln_s != 0.0:
        kwargs["spot"] = model.spot * float(np.exp(d_ln_s))
    if moves_factors and dx_ is not None:
        kwargs["x0"] = kernel_of(model).x0 + dx_
    return model.bump(**kwargs) if kwargs else model


def _pairs(x: FloatArray, antithetic: bool) -> FloatArray:
    return 0.5 * (x[0::2] + x[1::2]) if antithetic else x


def _se(samples: FloatArray) -> float:
    n = samples.shape[0]
    return float(samples.std(ddof=1) / np.sqrt(n)) if n > 1 else float("nan")


def _ratio(a: float, b: float, sa: FloatArray, sb: FloatArray) -> tuple[float, float]:
    """``a / b`` with the delta-method standard error from the per-path influence samples
    ``sa``, ``sb`` (means ``a``, ``b``)."""
    infl = (sa - a) / b - a / (b * b) * (sb - b)
    return a / b, _se(infl)


def _check(kind: str, allowed: Sequence[str], name: str) -> None:
    if kind not in allowed:
        raise ValueError(f"{name} must be one of {tuple(allowed)}, got {kind!r}")


