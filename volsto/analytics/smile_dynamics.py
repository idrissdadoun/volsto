@dataclass(frozen=True)
class SSRDecomposition:
    """Terms of book eq. 12.52 ``R_T = R^LV(Mkt) + (S^SV_T / S_T) [R^SV_T − R^LV(SV)]``."""

    T: float
    term_structure: str
    skew_sv_method: str
    R: float
    R_lv_market: float
    R_lv_sv: float
    R_sv: float
    skew_market: float
    skew_sv: float
    skew_sv_stderr: float
    skew_ratio: float
    sigma_hat_T: float
    sigma_0: float
    n_quad: int

    @property
    def R_stderr(self) -> float:
        """Propagated from ``S^SV_T`` only (zero for the order-one skew)."""
        return abs(self.R_sv - self.R_lv_sv) / abs(self.skew_market) * self.skew_sv_stderr

    def __repr__(self) -> str:
        return (
            f"SSRDecomposition(T={self.T:g}, {self.term_structure}/{self.skew_sv_method}: "
            f"R = {self.R:.4f} = R_LV(Mkt) {self.R_lv_market:.4f} + {self.skew_ratio:.4f} x "
            f"[R_SV {self.R_sv:.4f} - R_LV(SV) {self.R_lv_sv:.4f}]; S_T = {self.skew_market:.4f}, "
            f"S_SV = {self.skew_sv:.4f} ± {self.skew_sv_stderr:.4f}, sigma_0 = {self.sigma_0:.4f})"
        )


def atmf_variance_curve(surface: ImpliedSurface, t_max: float) -> ForwardVarianceCurve:
    """``σ²(t) = d(σ̂_t² t)/dt`` calibrated to the ATMF term structure of the surface (book
    p. 475: the deterministic volatility of the expansion), as a
    :class:`~volsto.market.varswap.ForwardVarianceCurve` of the ATMF total variances on a
    weekly grid (denser in the first month)."""
    short = np.array([1.0, 2.0, 3.0, 5.0, 10.0, 15.0, 22.0]) / 365.0
    weekly = np.arange(1, int(np.ceil(52 * t_max)) + 2) / 52.0
    mats = np.unique(np.concatenate((short[short < t_max], weekly[weekly < t_max], [t_max])))
    W = np.asarray(surface.atm_vol(mats), dtype=np.float64) ** 2 * mats
    if np.any(np.diff(W) <= 0):
        raise ValueError("the ATMF total variance of the surface is not increasing in T")
    return ForwardVarianceCurve(mats, W)


def _market_skew(surface: ImpliedSurface, t: FloatArray) -> FloatArray:
    fn = getattr(surface, "atm_skew", None)
    if callable(fn):
        return np.asarray(fn(t), dtype=np.float64)
    return atm_skew_numeric(surface, t)


def ssr_decomposition(
    model: Model,
    surface: ImpliedSurface,
    T: float,
    *,
    term_structure: str = "atmf",
    skew_sv_method: str = "order1",
    n_quad: int = 64,
    mixing_paths: int = 100_000,
    mixing_seed: int = 0,
    mixing_dt: float = 1.0 / 365.0,
) -> SSRDecomposition:
    """Book eq. 12.52 for an LSV calibrated to ``surface`` (its kernel supplies the SV terms).

    ``term_structure``: ``"flat"`` — the expansion around the constant ``σ_0 = σ̂_T`` (the ATMF
    vol of maturity ``T``): ``R^LV(Mkt) = 1 + (1/T) ∫₀ᵀ S_t/S_T dt`` (12.53), ``R^LV(SV) = 1 +
    (1/T) ∫₀ᵀ S^SV_t/S^SV_T dt`` (12.54) with ``S^SV`` from eq. 8.55 and ``R^SV`` from eq. 9.21;
    ``"atmf"`` — the book's choice for smiles with a marked term structure (p. 475, 477):
    ``σ²(t) = d(σ̂_t² t)/dt`` from the surface's ATMF vols, ``R^LV = 1 + (1/T) ∫₀ᵀ σ²(t)/(σ̂_t
    σ̂_T) S_t/S_T dt`` and its ``S^SV`` analogue, ``S^SV`` from eq. 9.18 and ``R^SV`` from eq.
    9.19 with ``ξ_0^t = σ²(t)``; ``"vs"`` — the same with the kernel's own forward-variance curve
    (VS vols).  The market skew ``S_t`` is the surface's analytic ATM skew when it has one,
    else a central difference; the ``1/√t`` short end is integrated with ``t = T u²``.
    ``skew_sv_method="mixing"`` replaces ``S^SV_T`` in the prefactor ``S^SV_T/S_T`` by the naked
    kernel's mixing-solution skew (book p. 478: computing ``S^SV_T`` numerically makes the
    decomposition exact when the smile is the kernel's own); the shape ``S^SV_t/S^SV_T`` inside
    ``R^LV(SV)`` stays at order one.  The book's sanity checks hold by construction:
    ``S_T = S^SV_T`` gives ``R = R^SV``, ``ν = 0`` gives ``R = R^LV(Mkt)``.  Measured on the cached
    1F ω = 3 reference LSV (8·10⁵ particles) against :func:`ssr_numerical` in
    ``tests/test_smile_dynamics.py::test_lsv_ssr_decomposition_vs_numerical`` (numbers in the
    test docstring).
    """
    _check(term_structure, TERM_STRUCTURES, "term_structure")
    _check(skew_sv_method, SKEW_SV_METHODS, "skew_sv_method")
    if T <= 0 or n_quad < 4:
        raise ValueError("T must be positive and n_quad >= 4")
    kernel = kernel_of(model)
    p = kernel.params
    u, wu = np.polynomial.legendre.leggauss(n_quad)
    u = 0.5 * (u + 1.0)
    wu = 0.5 * wu
    t = T * u * u  # t = T u²: dt = 2 T u du, so (1/T) ∫ f dt = Σ 2 u w f(t)
    weight = 2.0 * u * wu
    sig_T = float(surface.atm_vol(T))
    S_mkt_t = _market_skew(surface, t)
    S_mkt_T = float(_market_skew(surface, np.array([T]))[0])
    if term_structure == "flat":
        factor = np.ones_like(t)
        S_sv_t = np.asarray(atmf_skew_order1_flat(p, t), dtype=np.float64)
        S_sv_T = float(atmf_skew_order1_flat(p, T))
        R_sv = float(ssr_order1_flat(p, T))
        sigma_0 = sig_T
    else:
        curve = (
            atmf_variance_curve(surface, max(T, 1.5 / 12.0))
            if term_structure == "atmf"
            else kernel.xi0
        )
        sig_t = np.sqrt(np.asarray(curve.total_variance(t), dtype=np.float64) / t)
        sig_T_curve = float(np.sqrt(float(curve.total_variance(T)) / T))
        factor = np.asarray(curve.xi0(t), dtype=np.float64) / (sig_t * sig_T_curve)
        S_sv_t = np.array([atmf_skew_order1(p, curve, float(ti)) for ti in t])
        S_sv_T = float(atmf_skew_order1(p, curve, T))
        R_sv = float(ssr_order1(p, curve, T))
        sigma_0 = float(np.sqrt(float(curve.xi0(0.0))))
    R_lv_mkt = 1.0 + float(np.sum(weight * factor * S_mkt_t / S_mkt_T))
    R_lv_sv = 1.0 + float(np.sum(weight * factor * S_sv_t / S_sv_T))
    S_sv_se = 0.0
    if skew_sv_method == "mixing":
        S_sv_T, _, S_sv_se = mixing_atmf_skew(
            kernel, T, n_paths=mixing_paths, seed=mixing_seed, dt=mixing_dt
        )
    ratio = S_sv_T / S_mkt_T
    R = R_lv_mkt + ratio * (R_sv - R_lv_sv)
    return SSRDecomposition(
        float(T),
        term_structure,
        skew_sv_method,
        R,
        R_lv_mkt,
        R_lv_sv,
        R_sv,
        S_mkt_T,
        S_sv_T,
        S_sv_se,
        ratio,
        sig_T,
        sigma_0,
        int(n_quad),
    )


