@dataclass(frozen=True)
class ATMFVolOfVol:
    """Instantaneous lognormal vol of the ATMF vol of maturity ``T`` from the state-bump
    partials ``∂σ̂_T/∂(ln S, X¹, X²)`` and the state covariance (book eq. 12.56)."""

    T: float
    eps: float
    scheme: str
    atmf_vol: float
    atmf_vol_stderr: float
    sigma_0: float
    labels: tuple[str, ...]
    partials: FloatArray
    partials_stderr: FloatArray
    covariance: FloatArray
    variance_rate: float
    vol_of_vol: float
    vol_of_vol_stderr: float
    spot_vol_correlation: float
    ssr: float
    ssr_stderr: float
    skew: float
    skew_stderr: float
    vs_vol_of_vol: float
    n_paths: int

    def __repr__(self) -> str:
        parts = ", ".join(
            f"d/d{lab} = {v:.4f} ± {s:.4f}"
            for lab, v, s in zip(self.labels, self.partials, self.partials_stderr)
        )
        return (
            f"ATMFVolOfVol(T={self.T:g}: vol of vol = {self.vol_of_vol:.4f} ± "
            f"{self.vol_of_vol_stderr:.4f} (eq. 7.39 VS: {self.vs_vol_of_vol:.4f}), "
            f"corr(dS, dsigma) = {self.spot_vol_correlation:.3f}, R = {self.ssr:.3f} ± "
            f"{self.ssr_stderr:.3f}; {parts})"
        )


def _partials_from_quotes(
    model: Model,
    Ts: FloatArray,
    eps: float,
    scheme: str,
    mc: MonteCarlo,
    grid: TimeGrid,
    draws: GaussianDraws,
    base: _Quotes,
) -> tuple[FloatArray, FloatArray]:
    """State-bump partials of the ATMF vol: ``(values (nT, 1+nf), samples (n, nT, 1+nf))``."""
    scales = _bump_scales(model)
    nf = scales.size - 1
    k0 = np.array([0.0])
    vals = []
    samps = []
    for j in range(1 + nf):

        def bumped(sign: float, j: int = j) -> Model:
            if j == 0:
                return state_bump(model, d_ln_s=sign * eps * scales[0])
            dx = np.zeros(nf)
            dx[j - 1] = sign * eps
            return state_bump(model, dx=dx)

        up = _atmf_quotes(bumped(+1.0), Ts, k0, mc, grid, draws)
        if scheme == "central":
            dn = _atmf_quotes(bumped(-1.0), Ts, k0, mc, grid, draws)
            dn_v, dn_s = dn.iv[:, 0], dn.samples[:, :, 0]
            denom = 2.0 * eps * scales[j]
        else:
            dn_v, dn_s = base.iv[:, 1], base.samples[:, :, 1]
            denom = eps * scales[j]
        vals.append((up.iv[:, 0] - dn_v) / denom)
        samps.append((up.samples[:, :, 0] - dn_s) / denom)
    return np.stack(vals, axis=1), np.stack(samps, axis=2)


def _quadratic_form(
    p: FloatArray, samples: FloatArray, cov: FloatArray
) -> tuple[float, float, FloatArray]:
    """``p' C p`` with its delta-method standard error from the per-path samples ``(n, m)`` of
    ``p``; also returns the influence samples of the form."""
    g = 2.0 * cov @ p
    infl = (samples - p[None, :]) @ g
    return float(p @ cov @ p), _se(infl), infl


def atmf_vol_of_vol(
    model: Model,
    T: float,
    *,
    eps: float,
    sim: SimConfig,
    scheme: str = "central",
    skew_h: float = 0.01,
) -> ATMFVolOfVol:
    """Volatility of the ATMF volatility of maturity ``T`` (book §12.4.3, eq. 12.56).

    With ``L`` fixed, ``dσ̂_T = ∂σ̂_T/∂ln S d ln S + Σ_i ∂σ̂_T/∂X^i dX^i``; each partial is a
    central (or forward) difference of the ATMF vol under a bump of one state coordinate
    (``ln S_0 ± ε σ_0`` with ``L`` held in spot, ``X^i_0 ± ε``) on common random numbers, and

        ``Var(dσ̂_T)/dt = p' C p``,   ``C`` = :func:`state_covariance`,

    so the lognormal vol of vol is ``sqrt(p' C p) / σ̂_T``; the spot/vol correlation is
    ``(C p)_0 / (σ_0 sqrt(p' C p))`` and the SSR ``(σ_0 p_0 + Σ ρ_SXi p_i) / (σ_0 S_T)`` comes
    from the same partials (a cross-check of :func:`ssr_numerical`).  For pure SV the order-one
    prediction (book eqs. 7.36 / 12.47–12.49) is that ``σ̂_T`` carries the vol of vol of the VS vol
    of the same maturity, eq. 7.39 (``vs_vol_of_vol``, reported alongside); at ``T → 0`` both tend
    to ``ν``.  Checked by ``tests/test_smile_dynamics.py::test_atmf_vol_of_vol_short_maturity``.
    """
    _check(scheme, SCHEMES, "scheme")
    if eps <= 0 or T <= 0 or skew_h <= 0:
        raise ValueError("eps, T and skew_h must be positive")
    rho_s, _ = factor_loadings(model)
    Ts = np.array([float(T)])
    mc, grid, draws = _grid_and_draws(model, Ts, sim)
    base = _atmf_quotes(model, Ts, np.array([-skew_h, 0.0, skew_h]), mc, grid, draws)
    skew, skew_s = _skew(base, skew_h)
    vals, samps = _partials_from_quotes(model, Ts, eps, scheme, mc, grid, draws, base)
    p = vals[0]
    ps = samps[:, 0, :]
    cov = state_covariance(model)
    s0 = float(np.sqrt(cov[0, 0]))
    vr, vr_se, _ = _quadratic_form(p, ps, cov)
    if vr <= 0:
        raise ValueError("non-positive variance rate: the partials are pure noise at this size")
    sig = float(base.iv[0, 1])
    volvol = float(np.sqrt(vr)) / sig
    volvol_se = vr_se / (2.0 * np.sqrt(vr) * sig)
    corr = float(cov[0] @ p) / (s0 * float(np.sqrt(vr)))
    w = np.concatenate(([1.0], rho_s / s0))  # (σ_0 p_0 + Σ ρ_i p_i) / σ_0
    R, R_se = _ratio(float(w @ p), float(skew[0]), ps @ w, skew_s[:, 0])
    labels = ("ln S", *(f"X{i + 1}" for i in range(rho_s.size)))
    vs_ref = _kernel_vs_volvol(model, Ts)[0]
    return ATMFVolOfVol(
        float(T),
        float(eps),
        scheme,
        sig,
        _se(base.samples[:, 0, 1]),
        s0,
        labels,
        p,
        np.array([_se(ps[:, j]) for j in range(ps.shape[1])]),
        cov,
        vr,
        volvol,
        volvol_se,
        corr,
        R,
        R_se,
        float(skew[0]),
        _se(skew_s[:, 0]),
        float(vs_ref),
        int(sim.n_paths),
    )


def _kernel_vs_volvol(model: Model, Ts: FloatArray) -> FloatArray:
    """Eq. 7.39 with the kernel's curve; ``nan`` for a factor-less model."""
    if not isinstance(model, BergomiSV | LSV):
        return np.full(Ts.size, np.nan)
    k = kernel_of(model)
    return np.array([vs_vol_of_vol(k.params, float(T), k.xi0) for T in Ts])


def _kernel_vs_vol(model: Model, Ts: FloatArray) -> FloatArray:
    """``sqrt(W(T)/T)`` of the kernel's curve; ``nan`` for a factor-less model."""
    if not isinstance(model, BergomiSV | LSV):
        return np.full(Ts.size, np.nan)
    k = kernel_of(model)
    return np.sqrt(np.asarray(k.xi0.total_variance(Ts), dtype=np.float64) / Ts)


