@dataclass(frozen=True)
class ConditionalSmile:
    """Implied vols at horizon ``t`` conditional on ``ln S_t − ln F_t = spot_move``, strikes
    ``K = S_t F(T)/F(t) e^k`` (moneyness relative to the conditional forward)."""

    t: float
    T: float
    spot_move: float
    degree: int
    n_batches: int
    ks: FloatArray
    implied_vols: FloatArray
    stderr: FloatArray
    forward_ratio: float
    ln_spot: float
    x_conditional: FloatArray
    r2: FloatArray
    n_paths: int

    @property
    def atmf_vol(self) -> tuple[float, float]:
        """``(σ̂, stderr)`` at ``k = 0`` (raises if ``0`` is not among the strikes)."""
        i = int(np.flatnonzero(np.abs(self.ks) < 1e-12)[0])
        return float(self.implied_vols[i]), float(self.stderr[i])

    def to_dataframe(self) -> pd.DataFrame:
        return pd.DataFrame(
            {"k": self.ks, "implied_vol": self.implied_vols, "stderr": self.stderr, "r2": self.r2}
        )

    def __repr__(self) -> str:
        rows = [
            f"  k={k:+.4f}: iv={iv:.5f} ± {se:.5f}"
            for k, iv, se in zip(self.ks, self.implied_vols, self.stderr)
        ]
        head = (
            f"ConditionalSmile(t={self.t:.4g}, T={self.T:g}, spot_move={self.spot_move:+.4f}, "
            f"E[X|move]={np.round(self.x_conditional, 4).tolist()},\n"
        )
        return head + "\n".join(rows) + "\n)"


def conditional_smile(
    model: Model,
    t: float,
    spot_move: float,
    T: float,
    ks: ArrayLike,
    *,
    sim: SimConfig,
    degree: int = 3,
    n_batches: int = 10,
) -> ConditionalSmile:
    """Smile of maturity ``T`` seen at ``t`` conditional on the spot move ``ln S_t − ln F_t =
    spot_move`` (SPEC §15 Part 1).  The normalised payoffs ``cp_k (S_T/S_t − m e^k)⁺``, ``m =
    F(T)/F(t)`` (out-of-the-money: puts for ``k < 0``), are regressed on the polynomial basis in
    ``(ln S_t, X_t)`` (degree ``degree``, cross terms); the factors are regressed on ``ln S_t``
    alone (same degree) to give ``E[X_t | ln S_t]``; the fitted price at ``(ln F_t + spot_move,
    E[X_t | ·])`` inverts to the Black implied vol with forward ``m``, strike ``m e^k`` and
    maturity ``T − t``.  Standard errors by batch means.  Checked by
    ``tests/test_smile_dynamics.py::test_conditional_smile_first_order_move``: under pure SV the
    ATMF conditional vol moves by ``R_T S_T · spot_move`` to first order.
    """
    if degree < 1 or n_batches < 2:
        raise ValueError("need degree >= 1 and n_batches >= 2")
    ks_ = np.atleast_1d(np.asarray(ks, dtype=np.float64))
    hz = _simulate_horizon(model, t, T, sim)
    tau = T - t
    m = float(np.exp(hz.ln_f_T - hz.ln_f_t))
    cps = np.where(ks_ < 0, -1.0, 1.0)
    ret = np.exp(hz.ln_s_T - hz.ln_s_t)
    y = np.maximum(cps[None, :] * (ret[:, None] - m * np.exp(ks_)[None, :]), 0.0)
    raw = np.column_stack([hz.ln_s_t, hz.factors_t])
    mean = raw.mean(axis=0)
    scale = np.where(raw.std(axis=0) > 0, raw.std(axis=0), 1.0)
    x = _basis((raw - mean) / scale, degree)
    xs = _basis(((hz.ln_s_t - mean[0]) / scale[0])[:, None], degree)  # factors on ln S_t alone
    ln_star = hz.ln_f_t + spot_move
    n = sim.n_paths
    nf = model.n_factors
    r2 = np.zeros(ks_.size)
    x_star = np.zeros(nf)

    def stat(s: slice) -> FloatArray:
        nonlocal r2, x_star
        xst = np.zeros(nf)
        z_star = np.array([(ln_star - mean[0]) / scale[0]])
        for i in range(nf):
            b, _ = _fit(xs[s], hz.factors_t[s, i])
            xst[i] = float((_basis(z_star[:, None], degree) @ b)[0])
        feat = np.concatenate(([ln_star], xst))
        row = _basis(((feat - mean) / scale)[None, :], degree)
        prices = np.empty(ks_.size)
        r2_here = np.empty(ks_.size)
        for j in range(ks_.size):
            b, r2_here[j] = _fit(x[s], y[s, j])
            prices[j] = float((row @ b)[0])
        if s.start == 0 and s.stop == n:
            r2, x_star = r2_here, xst
        return np.asarray(implied_vol(prices, m, m * np.exp(ks_), tau, cps, 1.0), dtype=np.float64)

    iv, se = _batch_stat(stat, n, n_batches, sim.antithetic)
    return ConditionalSmile(
        float(t),
        float(T),
        float(spot_move),
        int(degree),
        int(n_batches),
        ks_,
        iv,
        se,
        m,
        float(ln_star),
        x_star,
        r2,
        int(n),
    )


