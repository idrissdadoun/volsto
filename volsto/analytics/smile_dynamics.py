"""Smile-dynamics analytics (SPEC §4.4, §7.14, §15 Part 1; Bergomi ch. 9 and §12.4).

Every quantity here is a property of the model *with its leverage function held fixed* (book
§12.3.2: the gamma/theta break-even levels of the mixed model are those generated by the model
with a fixed local volatility function), so nothing recalibrates.  For a pure
:class:`~volsto.models.bergomi.BergomiSV` model ``L ≡ 1``.

* :func:`ssr_numerical` — the skew-stickiness ratio at ``t = 0``, book eqs. 9.3 / 12.50,

      ``R_T = (1/S_T) E[dσ̂_T d ln S] / E[(d ln S)²]``,

  by the single-reprice estimator of §12.4.3 (§9.8 for pure SV): with ``L`` fixed the ATMF vol
  is a function ``σ̂_T(ln S, X¹, X²)``, hence

      ``R_T = (1/(S_T σ_0)) [σ_0 ∂σ̂_T/∂ln S + ρ_SX1 ∂σ̂_T/∂X¹ + ρ_SX2 ∂σ̂_T/∂X²]``,
      ``σ_0 = L(0, S_0) sqrt(ξ_0^0)``,

  evaluated with the joint bump ``(ln S_0 + ε σ_0, X_i = ε ρ_SXi)`` of the initial state and the
  ATMF option (strike = forward of the bumped spot) repriced under common random numbers;
  ``S_T`` is the model's own ATMF skew from two strikes around the forward on the same paths.
  ``kind="spot"`` bumps ``ln S_0`` alone (the risk layer's ``"model"`` regime move, M5), and
  ``kind="factors"`` the factors alone (the pure-SV estimator of §9.8).
* :func:`ssr_decomposition` — the order-one decomposition eq. 12.52,

      ``R_T = R_T^LV(Mkt) + (S_T^SV / S_T) [R_T^SV − R_T^LV(SV)]``,

  with ``R^LV`` from eqs. 12.53–12.54 (or their ATMF-term-structure forms, book p. 477),
  ``S^SV`` from eq. 8.55 / 9.18 and ``R^SV`` from eq. 9.21 / 9.19.
* :func:`ssr_short_horizon` — the independent estimator: simulate to ``t``, conditional ATMF
  vol by regression of the ``T``-maturity ATMF payoff on a polynomial basis in ``(ln S_t, X_t)``,
  regression of ``σ̂_T(t)`` on ``ln S_t`` across paths, divided by ``S_T``.
* :func:`atmf_vol_of_vol` — eq. 12.56: the same state-bump partials squared and combined with
  the instantaneous covariance of ``(ln S, X¹, X²)`` give the lognormal vol of the ATMF vol.
* :func:`conditional_smile` — the smile at horizon ``t`` conditional on a spot move.
* :func:`volvol_term_structure` — vol of VS vols: eq. 7.39 for the kernel and, by the same
  state-bump partials applied to the model's VS variance ``E[∫₀ᵀ L² ξ_u^u du]/T``, the
  leverage-included value (reduces to eq. 7.39 exactly for pure SV).

Standard errors are those of the per-path common-random-number differences (linearised implied
vols ``payoff / vega``) propagated by the delta method through ratios and quadratic forms; the
regression estimators use batch means.  Checked by ``tests/test_smile_dynamics.py``.
"""

