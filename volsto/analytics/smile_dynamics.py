@dataclass(frozen=True)
class SSRNumerical:
    """Skew-stickiness ratio from the state-bump estimator (book §12.4.3 / §9.8).

    ``numerator = [σ̂_T(+ε) − σ̂_T(−ε)] / (2ε)`` (vol per unit ``ε``), ``slope = numerator / σ_0 =
    E[dσ̂_T d ln S] / E[(d ln S)²]`` (the ATMF-vol shift per unit ``Δ ln S``, SPEC §7.2's
    ``SSR_T · s_T``) and ``R = slope / skew`` with ``skew = S_T`` the model's own ATMF skew.
    """

    T: float
    kind: str
    eps: float
    scheme: str
    R: float
    R_stderr: float
    slope: float
    slope_stderr: float
    numerator: float
    numerator_stderr: float
    skew: float
    skew_stderr: float
    skew_h: float
    sigma_0: float
    atmf_vol: float
    atmf_vol_stderr: float
    n_paths: int

    def __repr__(self) -> str:
        return (
            f"SSRNumerical(T={self.T:g}, {self.kind}: R = {self.R:.4f} ± {self.R_stderr:.4f}, "
            f"slope = {self.slope:.4f} ± {self.slope_stderr:.4f}, S_T = {self.skew:.4f} ± "
            f"{self.skew_stderr:.4f}, sigma_0 = {self.sigma_0:.4f}, eps = {self.eps:g})"
        )


def ssr_numerical_many(
    model: Model,
    Ts: ArrayLike,
    *,
    eps: float,
    sim: SimConfig,
    kind: str = "joint",
    scheme: str = "central",
    skew_h: float = 0.01,
) -> list[SSRNumerical]:
    """:func:`ssr_numerical` for several maturities on one path set (three simulations in all
    for the central scheme, two for the forward one)."""
    _check(kind, SSR_KINDS, "kind")
    _check(scheme, SCHEMES, "scheme")
    if eps <= 0 or skew_h <= 0:
        raise ValueError("eps and skew_h must be positive")
    Ts_ = np.unique(np.atleast_1d(np.asarray(Ts, dtype=np.float64)))
    if np.any(Ts_ <= 0):
        raise ValueError("maturities must be positive")
    rho_s, _ = factor_loadings(model)
    if kind == "factors" and rho_s.size == 0:
        raise ValueError("kind='factors' needs a model with factors")
    s0 = initial_vol(model)
    mc, grid, draws = _grid_and_draws(model, Ts_, sim)
    ks3 = np.array([-skew_h, 0.0, skew_h])
    base = _atmf_quotes(model, Ts_, ks3, mc, grid, draws)
    skew, skew_s = _skew(base, skew_h)

    def bumped(sign: float) -> Model:
        d_ln_s = sign * eps * s0 if kind in ("joint", "spot") else 0.0
        dx = sign * eps * rho_s if kind in ("joint", "factors") else None
        return state_bump(model, d_ln_s=d_ln_s, dx=dx)

    k0 = np.array([0.0])
    up = _atmf_quotes(bumped(+1.0), Ts_, k0, mc, grid, draws)
    if scheme == "central":
        dn = _atmf_quotes(bumped(-1.0), Ts_, k0, mc, grid, draws)
        num = (up.iv[:, 0] - dn.iv[:, 0]) / (2.0 * eps)
        num_s = (up.samples[:, :, 0] - dn.samples[:, :, 0]) / (2.0 * eps)
    else:
        num = (up.iv[:, 0] - base.iv[:, 1]) / eps
        num_s = (up.samples[:, :, 0] - base.samples[:, :, 1]) / eps
    out = []
    for i, T in enumerate(Ts_):
        R, R_se = _ratio(float(num[i]) / s0, float(skew[i]), num_s[:, i] / s0, skew_s[:, i])
        out.append(
            SSRNumerical(
                float(T),
                kind,
                float(eps),
                scheme,
                R,
                R_se,
                float(num[i]) / s0,
                _se(num_s[:, i]) / s0,
                float(num[i]),
                _se(num_s[:, i]),
                float(skew[i]),
                _se(skew_s[:, i]),
                float(skew_h),
                s0,
                float(base.iv[i, 1]),
                _se(base.samples[:, i, 1]),
                int(sim.n_paths),
            )
        )
    return out


def ssr_numerical(
    model: Model,
    T: float,
    *,
    eps: float,
    sim: SimConfig,
    kind: str = "joint",
    scheme: str = "central",
    skew_h: float = 0.01,
) -> SSRNumerical:
    """Numerical SSR at ``t = 0`` (book §12.4.3 for the LSV, §9.8 for pure SV; SPEC §4.4).

    ``kind="joint"``: ``(ln S_0 + ε σ_0, X_i + ε ρ_SXi)`` — the estimator of ``R_T``;
    ``"spot"``: ``ln S_0 + ε σ_0`` alone with the factors at zero (the ``"model"`` delta regime
    of the risk layer, whose ATM-vol shift per unit ``Δ ln S`` is this ``slope``); ``"factors"``:
    the factors alone.  ``scheme="central"`` uses ``±ε`` (three simulations), ``"forward"``
    ``+ε`` against the base.  Checked by ``tests/test_smile_dynamics.py::
    test_ssr_numerical_pure_sv_matches_order_one`` (eq. 9.21 within the order-one accuracy),
    ``test_ssr_numerical_eps_independence`` and, on the cached LSV, the decomposition and M5
    regime tests.
    """
    return ssr_numerical_many(
        model, [T], eps=eps, sim=sim, kind=kind, scheme=scheme, skew_h=skew_h
    )[0]


