def test_resume_recomputes_a_marking_point_whose_surface_changed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
) -> None:
    """A marking point's id names its surface, not the surface's content: the precompute records
    :func:`~volsto.viewers.grid.surface_digest` in the point's manifest and ``--resume``
    (:func:`~volsto.viewers.precompute.pending_steps`) recomputes a stored point whose digest
    differs from the grid surface's (or was never recorded), with a log line; the id format is
    unchanged.  No fit and no calibration: the fit is stubbed infeasible."""
    import logging

    from volsto.calibration.cache import LeverageCache
    from volsto.viewers import precompute
    from volsto.viewers.grid import surface_digest
    from volsto.viewers.store import PointResult, ResultsStore

    grid = load_grid(GRIDS / "default.yaml")
    point = next(
        p for p in enumerate_points(grid) if p.surface == "spx_2022-12-02" and p.mode == "marking"
    )
    assert point.id == "marking:spx_2022-12-02:ssr0.75:eps0.05"
    assert point.spec.surface.rhos is not None
    digest = surface_digest(point.spec)
    assert lv_key(point.spec) == "lv:" + digest
    flat = dataclasses.replace(
        point.spec, surface=dataclasses.replace(point.spec.surface, rhos=None)
    )
    assert surface_digest(flat) != digest

    def infeasible(p: object, surface: object) -> object:
        return dataclasses.replace(point, status="infeasible", resolved=True)

    monkeypatch.setattr(precompute, "resolve_marking", infeasible)
    cache = LeverageCache(tmp_path / "cache")
    res = precompute.compute_point(point, grid, cache, "none")
    assert res.manifest["surface_digest"] == digest
    assert not (tmp_path / "cache").exists()  # nothing calibrated
    store = ResultsStore(tmp_path / "store")
    store.write_point(res)
    assert precompute.pending_steps(point, store, cache, "none") == ()
    for stored in (surface_digest(flat), None):
        manifest = dict(res.manifest)
        if stored is None:
            manifest.pop("surface_digest")
        else:
            manifest["surface_digest"] = stored
        store.write_point(PointResult(res.point_id, res.row, res.tables, manifest))
        caplog.clear()
        with caplog.at_level(logging.INFO, logger="volsto.viewers.precompute"):
            assert precompute.pending_steps(point, store, cache, "none") == ("all",)
        assert any("stale" in r.getMessage() for r in caplog.records)
    # the other modes ignore the digest (their ids carry the content)
    lv_point = next(
        p for p in enumerate_points(grid) if p.surface == "spx_2022-12-02" and p.mode == "lv"
    )
    assert lv_point.id == lv_key(lv_point.spec)
