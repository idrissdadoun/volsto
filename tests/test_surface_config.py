def _committed_spec(rel: str) -> CalibrationSpec:
    path = STUDIES / rel
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if "spec" in raw:
        return from_mapping(CalibrationSpec, raw["spec"], path=str(path))
    return load_yaml(path, CalibrationSpec)


def _with_particles(spec: CalibrationSpec, n: int) -> CalibrationSpec:
    return dataclasses.replace(spec, particle=dataclasses.replace(spec.particle, n_particles=n))


def _m6_headline_keys() -> dict[str, str]:
    one = _with_particles(load_yaml(STUDIES / "lsv_reference_1f.yaml", CalibrationSpec), 800_000)
    two = _with_particles(load_yaml(STUDIES / "lsv_reference_2f.yaml", CalibrationSpec), 800_000)
    keys = {name: spec_key(s) for name, s in one_factor_variants(one, HEADLINE_OMEGAS).items()}
    keys["2F Table 8.2"] = spec_key(two)
    return keys


def _default_grid_digest() -> tuple[int, str]:
    grid = load_grid(GRIDS / "default.yaml")
    points = [p for p in enumerate_points(grid) if p.surface in ("placeholder", "spx_2022-12-30")]
    lines = sorted(f"{p.id}={p.cache_key}" for p in points)
    return len(lines), hashlib.sha256("\n".join(lines).encode()).hexdigest()


