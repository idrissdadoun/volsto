def test_keys_against_the_repository_cache_manifest() -> None:
    """Read-only: the recorded keys that addressed cache entries still do, and every one of them
    is reproduced by the current code (the manifest only grows)."""
    if not MANIFEST.exists():
        pytest.skip(f"no leverage-cache manifest at {MANIFEST}")
    keys = set(pd.read_parquet(MANIFEST, columns=["key"])["key"])
    current = {spec_key(_committed_spec(rel)) for rel in RECORDED_SPEC_KEYS}
    current |= set(_m6_headline_keys().values())
    for key in IN_MANIFEST_AT_RECORDING:
        assert key in keys, key
        assert key in current, key
    for name, old in FLATTENED_LV_IDS.items():
        # the deliberately changed ids addressed nothing
        assert old not in keys, name
    store = ROOT / "outputs" / "store" / "results" / "points"
    if store.is_dir():
        stored = {p.name for p in store.iterdir()}
        for old in FLATTENED_LV_IDS.values():
            assert old.replace(":", "__") not in stored


