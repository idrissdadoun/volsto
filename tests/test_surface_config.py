SURFACE_CLASSES = frozenset({"SSVISurface", "ESSVISurface"})
ALLOWED_CONSTRUCTORS: frozenset[tuple[str, str]] = frozenset(
    {
        ("volsto/market/surface.py", "surface_from_config"),
        # the importer builds its fitted surface from the fit's arrays, not from a config
        ("volsto/market/import_hdn.py", "fit_ssvi"),
    }
)
ALLOWED_CONFIG_READERS: frozenset[tuple[str, str]] = frozenset(
    {("volsto/market/loaders.py", "load_surface_config")}
)


def _name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _violations(path: Path, rel: str) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=rel)
    out: list[str] = []

    def visit(node: ast.AST, func: str) -> None:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            func = node.name
        if isinstance(node, ast.Call):
            f = node.func
            if (
                isinstance(f, ast.Attribute)
                and f.attr == "from_config"
                and _name(f.value) in SURFACE_CLASSES
            ):
                out.append(f"{rel}:{node.lineno} {_name(f.value)}.from_config (use the factory)")
            if _name(f) in SURFACE_CLASSES and (rel, func) not in ALLOWED_CONSTRUCTORS:
                out.append(f"{rel}:{node.lineno} {_name(f)}(...) in {func}")
            if (
                _name(f) == "load_yaml"
                and any(_name(a) == "SSVIConfig" for a in [*node.args, *(k.value for k in node.keywords)])
                and (rel, func) not in ALLOWED_CONFIG_READERS
            ):  # fmt: skip
                out.append(f"{rel}:{node.lineno} load_yaml(..., SSVIConfig) in {func}")
        if (
            isinstance(node, ast.Subscript)
            and isinstance(node.ctx, ast.Load)
            and isinstance(node.slice, ast.Constant)
            and node.slice.value == "ssvi"
            and (rel, func) not in ALLOWED_CONFIG_READERS
        ):
            out.append(f"{rel}:{node.lineno} raw ['ssvi'] section read in {func}")
        for child in ast.iter_child_nodes(node):
            visit(child, func)

    visit(tree, "<module>")
    return out


def test_every_surface_is_built_by_the_factory() -> None:
    """Walks every module of ``volsto/`` and ``scripts/``: no ``SSVISurface.from_config``, no
    SSVI / eSSVI constructor outside the factory (and the importer's fit), no ``SSVIConfig``
    read from a file and no raw ``["ssvi"]`` section read outside the loader.  A new site
    fails here instead of silently flattening an eSSVI snapshot."""
    files = sorted([*(ROOT / "volsto").rglob("*.py"), *(ROOT / "scripts").rglob("*.py")])
    assert len(files) > 50
    bad = [v for p in files for v in _violations(p, p.relative_to(ROOT).as_posix())]
    assert not bad, "\n".join(bad)
    # the walker sees what it forbids
    probe = ROOT / "tests" / "test_surface_config.py"
    found = _violations(probe, "tests/test_surface_config.py")
    assert any("SSVISurface.from_config" in v for v in found)
    assert any("ESSVISurface(...)" in v for v in found)


