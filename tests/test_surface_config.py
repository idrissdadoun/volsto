def test_rhos_field_validation_and_mapping() -> None:
    plain = SSVIConfig((0.5, 1.0), (0.2, 0.21), -0.7, 1.0, 0.5)
    assert plain.rhos is None and "rhos" not in to_mapping(plain)
    e = SSVIConfig((0.5, 1.0), (0.2, 0.21), -0.7, 1.0, 0.5, rhos=[-0.6, -0.8])  # type: ignore[arg-type]
    assert e.rhos == (-0.6, -0.8) and isinstance(e.rhos, tuple)
    assert to_mapping(e)["rhos"] == [-0.6, -0.8]
    assert from_mapping(SSVIConfig, to_mapping(e)) == e
    assert from_mapping(SSVIConfig, to_mapping(plain)) == plain
    hash(e)  # a frozen config stays hashable
    for bad in ((-0.6,), (-0.6, -1.0), (-0.6, float("nan")), (0.2, 1.5)):
        with pytest.raises(ValueError, match="rhos"):
            SSVIConfig((0.5, 1.0), (0.2, 0.21), -0.7, 1.0, 0.5, rhos=bad)
    with pytest.raises(ConfigError):
        from_mapping(
            SSVIConfig,
            {
                "atm_maturities": [1.0],
                "atm_vols": [0.2],
                "rho": 0.0,
                "eta": 1.0,
                "gamma": 0.5,
                "rhos": [1.2],
            },
        )


