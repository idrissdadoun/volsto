def _constant(pert: SurfacePerturbation) -> Callable[[float], SurfacePerturbation]:
    """A bump maker returning ``pert`` whatever the size (the engine's halving is not needed)."""

    def make(_size: float) -> SurfacePerturbation:
        return pert

    return make


def _skew_tent(slope: float) -> SurfacePerturbation:
    return SurfacePerturbation("skew_tent", {"pillars": [0.25, 1.0], "index": 0, "slope": slope})


def test_risk_bumps_on_the_essvi_surface() -> None:
    """Every perturbation kind layers on the eSSVI base (the risk engine's bumps), passes the
    arbitrage checks or halves through the engine, and moves the vols as defined."""
    base_spec = load_yaml(STUDIES / "lsv_reference_2f.yaml", CalibrationSpec)
    spec = dataclasses.replace(
        snapshot_spec(base_spec, ESSVI_SNAPSHOT), model=BergomiParams.one_factor(1.0, 1.0, -0.7)
    )
    state = RiskState(spec)
    base = surface_of(state)
    assert isinstance(base, ESSVISurface)
    engine = RiskEngine(BSBuilder(state), SimConfig(n_paths=2, chunk_size=2))
    ks = np.linspace(-0.3, 0.3, 13)
    for pert in PERTURBATIONS:
        bumped, achieved = engine.perturbed_state(state, _constant(pert), 1.0, label=pert.kind)
        assert achieved == 1.0, pert.kind
        surf = surface_of(bumped)
        assert isinstance(surf, PerturbedSurface) and surf.base.__class__ is ESSVISurface
        for T in (0.25, 1.0, 2.0):
            d = surf.implied_vol_k(ks, T) - base.implied_vol_k(ks, T)
            if pert.kind == "parallel":
                np.testing.assert_allclose(d, 0.01, atol=1e-12)
            elif pert.kind == "shift_k":
                np.testing.assert_allclose(
                    surf.implied_vol_k(ks, T), base.implied_vol_k(ks + 0.01, T), atol=1e-12
                )
            elif pert.kind == "atm_shift":
                np.testing.assert_allclose(d, 0.01 * base.atm_skew(max(T, 1 / 12)), atol=1e-5)
            assert np.all(np.isfinite(d)), pert.kind
    # a bump too large for the checks is halved on the eSSVI base as on the SSVI one
    big, achieved = engine.perturbed_state(state, _skew_tent, 0.8, label="big skew")
    assert achieved == 0.1 and isinstance(surface_of(big), PerturbedSurface)


