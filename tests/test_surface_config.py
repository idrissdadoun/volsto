def test_essvi_snapshot_config_carries_rhos(tmp_path: Path) -> None:
    raw = yaml.safe_load(ESSVI_SNAPSHOT.read_text(encoding="utf-8"))
    cfg = load_surface_config(ESSVI_SNAPSHOT)
    assert cfg.rhos == tuple(raw["essvi"]["rhos"])
    assert cfg.rho == raw["ssvi"]["rho"]  # the scalar stays (informational)
    assert load_surface_config(SSVI_SNAPSHOT).rhos is None
    # the grid's specs of the eSSVI surfaces carry the pillar rhos, and their LV ids moved
    grid = load_grid(GRIDS / "default.yaml")
    ref = reference_spec(grid)
    for name, old in FLATTENED_LV_IDS.items():
        spec = surface_spec(grid, grid.surface(name), ref)
        assert spec.surface.rhos is not None and len(spec.surface.rhos) >= 5, name
        assert lv_key(spec) != old
        flat = dataclasses.replace(spec, surface=dataclasses.replace(spec.surface, rhos=None))
        assert lv_key(flat) == old  # the old id was the flattened surface's
    # snapshot_spec and a spec round trip keep them; the key sees them
    base = load_yaml(STUDIES / "lsv_reference_2f.yaml", CalibrationSpec)
    spec = snapshot_spec(base, ESSVI_SNAPSHOT)
    assert spec.surface == cfg and spec.model == base.model
    dump_yaml(spec, tmp_path / "spec.yaml")
    back = load_yaml(tmp_path / "spec.yaml", CalibrationSpec)
    assert back == spec and spec_key(back) == spec_key(spec)
    flat = dataclasses.replace(spec, surface=dataclasses.replace(cfg, rhos=None))
    assert spec_key(flat) != spec_key(spec)
    # strictness of the essvi section
    text = ESSVI_SNAPSHOT.read_text(encoding="utf-8")
    for body, match in (
        ({"rhos": raw["essvi"]["rhos"], "extra": 1}, "exactly"),
        ({"rhos": raw["essvi"]["rhos"][:-1]}, "one correlation per ATM pillar"),
    ):
        bad = dict(raw, essvi=body)
        p = tmp_path / "bad.yaml"
        p.write_text(yaml.safe_dump(bad), encoding="utf-8")
        with pytest.raises(ConfigError, match=match):
            load_surface_config(p)
    both = dict(raw, ssvi={**raw["ssvi"], "rhos": raw["essvi"]["rhos"]})
    p = tmp_path / "both.yaml"
    p.write_text(yaml.safe_dump(both), encoding="utf-8")
    with pytest.raises(ConfigError, match="both"):
        load_surface_config(p)
    assert text == ESSVI_SNAPSHOT.read_text(encoding="utf-8")


def test_factory_builds_the_essvi_on_every_path() -> None:
    """The loader, the cache's market, the risk engine and the ``from_config`` alias all return
    the eSSVI surface of an eSSVI config, identical to a direct construction; the pure-SV
    kernel's ξ₀ (the leverage calibration's input) is the eSSVI's, not the flattened one's."""
    cfg = load_surface_config(ESSVI_SNAPSHOT)
    base = load_yaml(STUDIES / "lsv_reference_2f.yaml", CalibrationSpec)
    spec = snapshot_spec(base, ESSVI_SNAPSHOT)
    fc = ForwardCurve.from_config(spec.market)
    t, v = np.asarray(cfg.atm_maturities), np.asarray(cfg.atm_vols)
    assert cfg.rhos is not None
    direct = ESSVISurface(
        t, v * v * t, cfg.rhos, cfg.eta, cfg.gamma, fc, fc.rate_curve, max_maturity=3.0
    )
    ks = np.linspace(-1.0, 1.0, 41)[None, :]
    ts = np.array([0.1, 0.5, 1.0, 1.7, 2.5, 3.0])[:, None]
    w0 = direct.total_variance(ks, ts)
    surfaces = {
        "factory": surface_from_config(cfg, fc, fc.rate_curve),
        "alias": SSVISurface.from_config(cfg, fc, fc.rate_curve),
        "loader": load_ssvi_surface(ESSVI_SNAPSHOT),
        "risk": surface_of(RiskState(spec)),
    }
    for name, s in surfaces.items():
        assert isinstance(s, ESSVISurface), name
        np.testing.assert_array_equal(s.total_variance(ks, ts), w0, err_msg=name)
    flat_cfg = dataclasses.replace(cfg, rhos=None)
    flat = surface_from_config(flat_cfg, fc, fc.rate_curve)
    assert type(flat) is SSVISurface
    assert np.max(np.abs(flat.total_variance(ks, ts) - w0)) > 1e-3  # the flattening mattered
    # the cache's market: eSSVI surface and its variance-swap strip in the kernel
    _, surface, kernel = build_market(spec)
    assert isinstance(surface, ESSVISurface)
    _, _, kernel_flat = build_market(dataclasses.replace(spec, surface=flat_cfg))
    grid_t = np.linspace(0.05, 3.0, 30)
    xi_e, xi_f = kernel.xi0.xi0(grid_t), kernel_flat.xi0.xi0(grid_t)
    assert np.max(np.abs(xi_e - xi_f)) > 1e-4
    k_e = float(varswap_strike(surface, 2.0))
    k_f = float(varswap_strike(flat, 2.0))
    print(
        f"2y variance-swap vol: eSSVI {np.sqrt(k_e) * 100:.3f}% vs mean-rho SSVI "
        f"{np.sqrt(k_f) * 100:.3f}%; max |xi0 difference| {np.max(np.abs(xi_e - xi_f)):.2e}"
    )
    assert abs(np.sqrt(k_e) - np.sqrt(k_f)) > 1e-4
    # the local-vol builder's Dupire runs on the eSSVI surface
    lv = LocalVolSurface.from_implied(surface, spec.local_vol)
    assert np.all(np.isfinite(lv.local_var)) and np.all(lv.local_var > 0)


def _repaired_gate_snapshot() -> Path | None:
    if not GATE_SNAPSHOTS.is_dir():
        return None
    for path in sorted(GATE_SNAPSHOTS.glob("spx_*.yaml")):
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
        if raw.get("provenance", {}).get("fit", {}).get("calendar_repaired") and "essvi" in raw:
            return path
    return None


def test_calendar_certificate_survives_the_config_path(tmp_path: Path) -> None:
    """SPEC §13.1's invariant — ``∂_T w ≥ margin`` proven on ``|k| ≤ 3`` — holds on the surface
    the leverage cache builds from the snapshot's spec: the importer's certificate is
    re-proven on the rebuilt surface with the importer's own lower bound.  A repaired day of the
    M10 Part 0 history when present; always a synthetic eSSVI written and read back."""
    base = load_yaml(STUDIES / "lsv_reference_2f.yaml", CalibrationSpec)
    gate = _repaired_gate_snapshot()
    if gate is not None:
        fit = yaml.safe_load(gate.read_text(encoding="utf-8"))["provenance"]["fit"]
        _, surface, _ = build_market(snapshot_spec(base, gate))
        assert isinstance(surface, ESSVISurface)
        cert = surface.calendar_certificate(
            k_abs=fit["calendar_k_abs"], floor=fit["calendar_floor"]
        )
        print(f"{gate.name}: {cert.status}, lower bound {cert.lower_bound:.6e} (importer "
              f"{fit['calendar_lower_bound']:.6e}), min {cert.min_value:.6e}")  # fmt: skip
        assert cert.certified
        assert cert.lower_bound == pytest.approx(fit["calendar_lower_bound"], rel=1e-9)
        assert cert.min_value == pytest.approx(fit["calendar_min_dw_dt"], rel=1e-9)
    # synthetic: a certified eSSVI, written as a snapshot and rebuilt from the config
    fc = ForwardCurve.flat(100.0, 0.02, 0.01)
    pil = np.array([1 / 12, 0.25, 0.5, 1.0, 2.0, 3.0])
    vols = np.array([0.24, 0.22, 0.21, 0.205, 0.205, 0.21])
    rhos = np.array([-0.45, -0.55, -0.62, -0.68, -0.70, -0.70])
    direct = ESSVISurface(pil, vols**2 * pil, rhos, 0.9, 0.45, fc, fc.rate_curve, max_maturity=3.0)
    cert0 = direct.calendar_certificate(k_abs=3.0, floor=1e-4)
    assert cert0.certified
    snap = {
        "market": {
            "spot": 100.0,
            "rate_curve": {"times": [1.0], "rates": [0.02]},
            "dividend_curve": {"times": [1.0], "rates": [0.01]},
        },
        "ssvi": {
            "atm_maturities": pil.tolist(),
            "atm_vols": vols.tolist(),
            "rho": float(rhos.mean()),
            "eta": 0.9,
            "gamma": 0.45,
            "max_maturity": 3.0,
        },
        "essvi": {"rhos": rhos.tolist()},
    }
    path = tmp_path / "synthetic.yaml"
    path.write_text(yaml.safe_dump(snap), encoding="utf-8")
    _, rebuilt, _ = build_market(snapshot_spec(base, path))
    assert isinstance(rebuilt, ESSVISurface)
    cert1 = rebuilt.calendar_certificate(k_abs=3.0, floor=1e-4)
    assert cert1.certified
    assert cert1.lower_bound == pytest.approx(cert0.lower_bound, rel=1e-9)


